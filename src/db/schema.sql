    ON public.document_rows(document_id);

CREATE INDEX idx_document_rows_table_id
    ON public.document_rows(table_id);

CREATE INDEX idx_financial_metrics_document_id
    ON public.financial_metrics(document_id);

CREATE INDEX idx_calculated_metrics_document_id
    ON public.calculated_metrics(document_id);

CREATE INDEX idx_metric_variance_alerts_document_id
    ON public.metric_variance_alerts(document_id);

CREATE INDEX idx_row_change_log_document_id
    ON public.row_change_log(document_id);

CREATE INDEX idx_row_change_log_previous_document_id
    ON public.row_change_log(previous_document_id);

CREATE INDEX idx_user_documents_document_id
    ON public.user_documents(document_id);

CREATE INDEX idx_user_storage_logs_user_id
    ON public.user_storage_logs(user_id);

